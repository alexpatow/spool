// Writes the files the `spool` binary serves as the studio: the page, its
// script and its style sheet, built from this package.
//
//   bun scripts/build.ts           writes the files
//   bun scripts/build.ts --check   fails if a file is out of date

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const outputDir = join(root, "../../crates/spool-cli/src/studio");

/** The files the server has a route for. A build that makes another is a mistake. */
const FILES = ["index.html", "studio.js", "studio.css"];

// The packages are MIT-licensed, and the licence asks that its text travels
// with copies of the code.
function notice(name: string): string {
  const version = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8")).version;
  const licence = readFileSync(join(root, "node_modules", name, "LICENSE"), "utf8").trim();
  return `${name} ${version}\n\n${licence}`;
}

function banner(): string {
  const lines = [
    "Generated by packages/studio/scripts/build.ts from packages/studio.",
    "Do not edit: change the source and run `bun run build` in packages/studio.",
    "",
    "This file contains code of the following packages.",
    "",
    notice("react"),
    "",
    notice("react-dom"),
    "",
    notice("scheduler"),
  ]
    .join("\n")
    .split("\n");
  return lines.map((line) => (line ? `// ${line}` : "//")).join("\n");
}

async function generate(): Promise<Map<string, string>> {
  const result = await build({ root, logLevel: "warn", build: { write: false } });
  const outputs = Array.isArray(result) ? result : [result];
  const files = new Map<string, string>();
  for (const output of outputs) {
    if (!("output" in output)) throw new Error("the studio was built to watch, not to write");
    for (const file of output.output) {
      const contents = file.type === "chunk" ? file.code : file.source;
      const text = typeof contents === "string" ? contents : new TextDecoder().decode(contents);
      files.set(file.fileName, file.fileName === "studio.js" ? `${banner()}\n\n${text}` : text);
    }
  }
  const names = [...files.keys()].sort();
  if (names.join() !== [...FILES].sort().join()) {
    throw new Error(`the build made ${names.join(", ")}, and the server serves ${FILES.join(", ")}`);
  }
  return files;
}

const generated = await generate();
if (process.argv.includes("--check")) {
  const stale = [...generated].filter(([name, contents]) => {
    const path = join(outputDir, name);
    return !existsSync(path) || readFileSync(path, "utf8") !== contents;
  });
  if (stale.length > 0) {
    for (const [name] of stale) console.error(`${join(outputDir, name)} is out of date`);
    console.error("run `bun run build` in packages/studio");
    process.exit(1);
  }
} else {
  mkdirSync(outputDir, { recursive: true });
  for (const [name, contents] of generated) {
    writeFileSync(join(outputDir, name), contents);
    console.log(`wrote ${join(outputDir, name)}`);
  }
}
