/** The licence of a package that is published without the text of it. */
const UNFILED: Record<string, string> = {
  "@stylexjs/stylex": `MIT License\n\nCopyright (c) Meta Platforms, Inc. and affiliates.\n\n${MIT}`,
};

// The licences of the packages ask that their text travels with copies of
// the code, so each file begins with the text for what it holds.
function notice(directory: string): string {
  const { name, version, license } = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
  const file = readdirSync(directory).find((entry) => /^licen[cs]e(\.md|\.txt)?$/i.test(entry));
  const text = file ? readFileSync(join(directory, file), "utf8").trim() : UNFILED[name];
  if (!text) throw new Error(`${name} is in the studio, and its licence (${license}) has no text to put beside it`);
  return `${name} ${version}\n\n${text}`;
}

function comment(lines: string[], line: (text: string) => string): string {
  return lines
    .join("\n")
    .split("\n")
    .map((text) => line(text.trimEnd()))
    .join("\n");
}

const GENERATED = [
  "Generated by packages/studio/scripts/build.ts from packages/studio.",
  "Do not edit: change the source and run `bun run build` in packages/studio.",
  "",
];

/** The directory of the package a module of the bundle comes from, if it comes from one. */
function packageOf(module: string): string | null {
  const found = /^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(module.replace(/^\0/, ""));
  return found ? found[1]! : null;
}

function scriptBanner(modules: string[]): string {
  const packages = [...new Set(modules.map(packageOf).filter((directory) => directory !== null))];
  const notices = packages.map(notice).sort();
  // The components of the page are Shelf's, copied into src/components/ui.
  const shelf = `Shelf UI components\n\n${readFileSync(join(root, "node_modules/@shelfui/cli/LICENSE"), "utf8").trim()}`;
  const lines = [
    ...GENERATED,
    "This file contains code of the following.",
    "",
    ...[...notices, shelf].flatMap((text) => [text, ""]),
  ];
  return comment(lines.slice(0, -1), (text) => (text ? `// ${text}` : "//"));
}

function styleBanner(): string {
  const notices = FONTS.map((name) => notice(join(root, "node_modules", name)));
  const lines = [
    ...GENERATED,
    "The fonts this file names are served beside it. They are of the following.",
    "",
    ...notices.flatMap((text) => [text, ""]),
  ];
  // A licence may hold what would end the comment.
  return `/*\n${comment(lines.slice(0, -1), (text) => (text ? ` * ${text.replaceAll("*/", "* /")}` : " *"))}\n */`;
}

async function generate(): Promise<Map<string, Buffer>> {
  const result = await build({ root, logLevel: "warn", build: { write: false } });
  const outputs = Array.isArray(result) ? result : [result];
  const files = new Map<string, Buffer>();
  for (const output of outputs) {
    if (!("output" in output)) throw new Error("the studio was built to watch, not to write");
    for (const file of output.output) {
      if (file.type === "chunk") {
        files.set(file.fileName, Buffer.from(`${scriptBanner(Object.keys(file.modules))}\n\n${file.code}`));
      } else if (file.fileName === "studio.css") {
        files.set(file.fileName, Buffer.from(`${styleBanner()}\n\n${file.source}`));
      } else {
        files.set(file.fileName, Buffer.from(file.source));
      }
    }
  }
  const names = [...files.keys()].sort();
  if (names.join() !== [...FILES].sort().join()) {
    throw new Error(`the build made ${names.join(", ")}, and the server serves ${FILES.join(", ")}`);
  }
  return files;
}

const generated = await generate();
if (process.argv.includes("--check")) {
  const stale = [...generated].filter(([name, contents]) => {
    const path = join(outputDir, name);
    return !existsSync(path) || !readFileSync(path).equals(contents);
  });
  if (stale.length > 0) {
    for (const [name] of stale) console.error(`${join(outputDir, name)} is out of date`);
    console.error("run `bun run build` in packages/studio");
    process.exit(1);
  }
} else {
  mkdirSync(outputDir, { recursive: true });
  for (const [name, contents] of generated) {
    writeFileSync(join(outputDir, name), contents);
    console.log(`wrote ${join(outputDir, name)}`);
  }
}
