// Writes src/types.ts from the JSON Schema of the API.
//
//   bun scripts/generate-types.ts           writes the file
//   bun scripts/generate-types.ts --check   fails if the file is out of date
//
// The schema is the one `spool schema` prints. It uses a small part of JSON
// Schema, and this script handles that part and refuses anything else, so a
// form it does not know cannot turn into a wrong type unnoticed.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Schema = boolean | { [key: string]: unknown };

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(here, "../../../schema/spool-api.v1.schema.json");
const outputPath = join(here, "../src/types.ts");

// Keys that say nothing about the TypeScript type.
const ANNOTATIONS = new Set(["description", "default", "format", "minimum", "maximum", "pattern", "title"]);

function fail(where: string, message: string): never {
  throw new Error(`${where}: ${message}`);
}

function comment(description: unknown, indent: string): string {
  if (typeof description !== "string" || description === "") return "";
  const lines = description.replaceAll("*/", "*\\/").split("\n");
  return `${indent}/**\n${lines.map((line) => `${indent} *${line ? ` ${line}` : ""}`).join("\n")}\n${indent} */\n`;
}

function primitive(name: unknown, where: string): string {
  switch (name) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    default:
      return fail(where, `unknown type ${JSON.stringify(name)}`);
  }
}

function union(members: string[]): string {
  return [...new Set(members)].join(" | ");
}

function typeOf(schema: Schema, where: string, indent: string): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  const keys = Object.keys(schema).filter((key) => !ANNOTATIONS.has(key));
  const only = (...allowed: string[]) => {
    const extra = keys.filter((key) => !allowed.includes(key));
    if (extra.length > 0) fail(where, `unhandled keys ${extra.join(", ")}`);
  };

  if (keys.length === 0) return "unknown";
  if ("$ref" in schema) {
    only("$ref");
    const ref = schema.$ref as string;
    if (!ref.startsWith("#/$defs/")) fail(where, `unknown reference ${ref}`);
    return ref.slice("#/$defs/".length);
  }
  if ("oneOf" in schema || "anyOf" in schema) {
    only("oneOf", "anyOf");
    const members = (schema.oneOf ?? schema.anyOf) as Schema[];
    return union(members.map((member, index) => typeOf(member, `${where}[${index}]`, indent)));
  }
  if ("const" in schema) {
    only("const", "type");
    return JSON.stringify(schema.const);
  }
  if ("enum" in schema) {
    only("enum", "type");
    return union((schema.enum as unknown[]).map((value) => JSON.stringify(value)));
  }
  if (Array.isArray(schema.type)) {
    // Several types at once: each is read as if it stood alone.
    return union(schema.type.map((name) => typeOf({ ...schema, type: name }, where, indent)));
  }
  if (schema.type === "null") return "null";
  if (schema.type === "array") {
    only("type", "items");
    const items = typeOf((schema.items ?? true) as Schema, `${where}[]`, indent);
    return /[ |]/.test(items) ? `Array<${items}>` : `${items}[]`;
  }
  if (schema.type === "object") {
    only("type", "properties", "required", "additionalProperties");
    const properties = (schema.properties ?? {}) as Record<string, Schema>;
    const names = Object.keys(properties);
    if (names.length === 0) return "Record<string, unknown>";
    const required = new Set((schema.required ?? []) as string[]);
    const inner = `${indent}  `;
    const fields = names.map((name) => {
      const property = properties[name]!;
      const description = typeof property === "object" ? property.description : undefined;
      const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
      const type = typeOf(property, `${where}.${name}`, inner);
      return `${comment(description, inner)}${inner}${key}${required.has(name) ? "" : "?"}: ${type};`;
    });
    return `{\n${fields.join("\n")}\n${indent}}`;
  }
  only("type");
  return primitive(schema.type, where);
}

function generate(): string {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8")) as { $defs: Record<string, Schema> };
  const parts = [
    "// Generated by scripts/generate-types.ts from schema/spool-api.v1.schema.json.",
    "// Do not edit: change the server's types, run `spool schema`, and generate again.",
    "//",
    "// Positions in the log and run IDs are 64-bit integers on the server and",
    "// numbers here, which is exact up to 2^53.",
    "",
  ];
  for (const name of Object.keys(schema.$defs).sort()) {
    const definition = schema.$defs[name]!;
    const description = typeof definition === "object" ? definition.description : undefined;
    let declaration: string;
    if (typeof definition === "object" && ("oneOf" in definition || "anyOf" in definition)) {
      const members = (definition.oneOf ?? definition.anyOf) as Schema[];
      const types = [...new Set(members.map((member, index) => typeOf(member, `${name}[${index}]`, "    ")))];
      declaration = types.some((type) => type.includes("\n"))
        ? `export type ${name} =\n${types.map((type) => `  | ${type}`).join("\n")};`
        : `export type ${name} = ${types.join(" | ")};`;
    } else {
      const type = typeOf(definition, name, "");
      declaration = type.startsWith("{") ? `export interface ${name} ${type}` : `export type ${name} = ${type};`;
    }
    parts.push(`${comment(description, "")}${declaration}`, "");
  }
  return parts.join("\n");
}

const generated = generate();
if (process.argv.includes("--check")) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    console.error("src/types.ts is out of date: run `bun run generate`");
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${outputPath}`);
}
