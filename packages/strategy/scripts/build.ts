// Writes the one file the engine ships as the TypeScript strategy helper:
// src/index.ts with the Parquet reader and writer it imports.
//
//   bun scripts/build.ts           writes the file
//   bun scripts/build.ts --check   fails if the file is out of date

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const outputPath = join(root, "../../crates/spool/assets/usercode/spool.js");

// The two packages are MIT-licensed, and the licence asks that its text
// travels with copies of the code.
function notice(name: string): string {
  const version = JSON.parse(readFileSync(join(root, "node_modules", name, "package.json"), "utf8")).version;
  const licence = readFileSync(join(root, "node_modules", name, "LICENSE"), "utf8").trim();
  return `${name} ${version}\n\n${licence}`;
}

async function generate(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    target: "bun",
    format: "esm",
  });
  if (!result.success || result.outputs.length !== 1) {
    throw new AggregateError(result.logs, "the helper did not build");
  }
  const code = await result.outputs[0]!.text();
  const banner = [
    "Generated by packages/strategy/scripts/build.ts from packages/strategy/src/index.ts.",
    "Do not edit: change the source and run `bun run build` in packages/strategy.",
    "",
    "This file contains code of the following packages.",
    "",
    notice("hyparquet"),
    "",
    notice("hyparquet-writer"),
  ]
    .join("\n")
    .split("\n")
    .map((line) => (line ? `// ${line}` : "//"))
    .join("\n");
  return `${banner}\n\n${code}`;
}

const generated = await generate();
if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== generated) {
    console.error(`${outputPath} is out of date: run \`bun run build\` in packages/strategy`);
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${outputPath}`);
}
